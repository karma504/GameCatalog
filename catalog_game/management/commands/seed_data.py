def age_of(birth):
    today = timezone.localdate()
    return today.year - birth.year - ((today.month, today.day) < (birth.month, birth.day))


def min_age(game):
    """Мінімальний вік за віковим рейтингом гри («16+» → 16; без рейтингу → 0)."""
    digits = ''.join(ch for ch in (game.age_rating or '') if ch.isdigit())
    return int(digits) if digits else 0


class Command(BaseCommand):
    help = 'Заповнює каталог іграми, розробниками, жанрами й платформами (безпечно до повторного запуску)'

    def add_arguments(self, parser):
        parser.add_argument('--no-demo-users', action='store_true',
                            help='не створювати демо-акаунти, відгуки й обране')
        parser.add_argument('--with-demo-users', action='store_true', help=argparse.SUPPRESS)
        parser.add_argument('--keep-prices', action='store_true',
                            help='не змінювати ціни ігор, що вже є в каталозі')

    def handle(self, *args, **opts):
        genres = {n: Genre.objects.get_or_create(name_genre=n, defaults={'descriptions': d})[0]
                  for n, d in GENRES.items()}
        platforms = {n: Platform.objects.get_or_create(name_platform=n, defaults={'manufacturer': m})[0]
                     for n, m in PLATFORMS.items()}

        devs = {}
        for name, city, country, year, site in DEVELOPERS:
            dev = Developers.objects.filter(name_dev__iexact=name).first()
            if dev is None:
                dev = Developers.objects.create(name_dev=name, city_dev=city, country_dev=country,
                                                founded_year=year, website=site)
            devs[name] = dev

        added = updated = 0
        for (title, dev, size, released, age, price, gl, pl, appid, site, desc) in GAMES:
            game = Games.objects.filter(title__iexact=title).first()
            image = steam(appid) if appid else None
            site = site or (f'https://store.steampowered.com/app/{appid}/' if appid else None)
            if game is None:
                game = Games.objects.create(
                    title=title, id_dev=devs[dev], file_size_gb=Decimal(size) if size else None, release_date=released,
                    age_rating=age, price=Decimal(price), description=desc,
                    official_url=site, image_url=image)
                added += 1
            else:
                changed = []
                if not game.image_url and image:
                    game.image_url = image
                    changed.append('image_url')
                if not game.official_url and site:
                    game.official_url = site
                    changed.append('official_url')
                if not opts['keep_prices'] and game.price != Decimal(price):
                    game.price = Decimal(price)
                    changed.append('price')
                if changed:
                    game.save(update_fields=changed)
                    updated += 1
            have_g = set(game.genres.values_list('pk', flat=True))
            have_p = set(game.platforms.values_list('pk', flat=True))
            game.genres.add(*[genres[g] for g in with_single(title, gl) if genres[g].pk not in have_g])
            game.platforms.add(*[platforms[p] for p in pl if platforms[p].pk not in have_p])

        msg = (f'Готово. Нових ігор: {added}, доповнено наявних: {updated}. '
               f'Усього ігор у каталозі: {Games.objects.count()}.')
        self.stdout.write(self.style.SUCCESS(msg))

        if not opts['no_demo_users']:
            self._demo()
        self.stdout.write('Перевірити посилання: python manage.py check_links')

    def _demo(self):
        now = timezone.now()
        first_seen = {}
        for _, key, _, days, _ in DEMO_REVIEWS:
            first_seen[key] = max(first_seen.get(key, 0), days)
        for key, _, _, days in DEMO_WISHES:
            first_seen[key] = max(first_seen.get(key, 0), days)

        users, created = {}, 0
        for key, email, first_name, last_name, age in DEMO_USERS:
            user = Users.objects.filter(email__iexact=email).first()
            if user is None:
                birth = OLD_BIRTHS.get(key) or years_ago(age, extra_days=sum(map(ord, key)) % 300 + 1)
                registered = now - timedelta(days=first_seen.get(key, 0) + 10 + sum(map(ord, key)) % 30)
                user = Users.objects.create_user(email=email, password=DEMO_PASSWORD, firstname=first_name,
                                                 last_name=last_name, date_of_birth=birth,
                                                 date_registration=registered)
                created += 1
            users[key] = user

        games = {g.title.lower(): g for g in Games.objects.all()}
        reviews = wishes = skipped = 0
        for n, (title, key, rating, days, comment) in enumerate(DEMO_REVIEWS):
            game, user = games.get(title.lower()), users[key]
            if game is None or (user.age is not None and user.age < min_age(game)):
                skipped += 1
                continue
            when = now - timedelta(days=days, hours=n * 7 % 24, minutes=n * 13 % 60)
            _, new = Reviews.objects.get_or_create(id_user=user, id_game=game,
                                                   defaults={'rating': rating, 'comment': comment, 'review_date': when})
            reviews += new
        for n, (key, title, note, days) in enumerate(DEMO_WISHES):
            game, user = games.get(title.lower()), users[key]
            if game is None or (user.age is not None and user.age < min_age(game)):
                skipped += 1
                continue
            when = now - timedelta(days=days, hours=n * 5 % 24, minutes=n * 11 % 60)
            _, new = Wishlist.objects.get_or_create(id_user=user, id_game=game,
                                                    defaults={'note': note, 'added_date': when})
            wishes += new

        self.stdout.write(self.style.SUCCESS(
            f'Демо-дані: нових користувачів {created}, відгуків {reviews}, записів в обраному {wishes}'
            + (f', пропущено {skipped} (гра не знайдена або вікове обмеження)' if skipped else '') + '.'))
        self.stdout.write(f'Пароль усіх демо-акаунтів: {DEMO_PASSWORD}. Приклад входу: {DEMO_USERS[5][1]}')
