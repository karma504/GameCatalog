def with_single(title, genre_names):
    """Додає жанр «Одиночна гра» (в кінець списку), якщо в грі є одиночний режим."""
    genre_names = list(genre_names)
    if SINGLE not in genre_names and title not in MULTIPLAYER_ONLY:
        genre_names.append(SINGLE)
    return genre_names

